void register_words() {
    static const bool once = [] {
        i18n::set_default_domain("xdesk");
        i18n::register_catalogue("xdesk", "en", kEn);
        i18n::register_catalogue("xdesk", "zh", kZh);
        return true;
    }();
    (void)once;
}

bool chinese() { return i18n::language().starts_with("zh"); }

