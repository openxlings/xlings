#!/usr/bin/env python3
"""The Luban OS icon, made from the app's own craftsman (design 2026-10-19 §14).

The craftsman with his hammer raised (`kCraft0`) and the colours he is drawn
in are read from luban/host/luban-os/src/art/art.cpp -- one source: change him there
and run

    python3 luban/tools/luban_os_icon.py            # writes luban/host/luban-os/share/luban-os.svg
    python3 luban/tools/luban_os_icon.py --check    # the lint: the icon is what the grid makes

Each pixel is a square (runs of one colour in a row are one rect), drawn with
crisp edges on a rounded tile, so the icon stays pixel art at any size.
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent.parent
art = root / "luban/host/luban-os/src/art/art.cpp"
icon = root / "luban/host/luban-os/share/luban-os.svg"

TILE = 20           # the tile is 20 x 20 grid units, the craftsman's 16 x 16 inside
TILE_COLOR = "#3b5dc9"


def craftsman(src: str) -> list[str]:
    m = re.search(r"constexpr Rows kCraft0\{(.*?)\};", src, re.S)
    if not m:
        sys.exit(f"{art}: kCraft0 not found")
    rows = re.findall(r'"([^"]*)"', m.group(1))
    if len(rows) != 16 or any(len(r) != 16 for r in rows):
        sys.exit(f"{art}: kCraft0 is not 16 rows of 16")
    return rows


def palette(src: str) -> dict[str, str]:
    body = src[src.index("void badge("):]
    body = body[:body.index("\n}\n")]
    return {c: f"#{v.lower()}" for c, v in re.findall(r"case '(.)': return rgb_\(0x([0-9a-fA-F]{6})\);", body)}


def svg(rows: list[str], colors: dict[str, str]) -> str:
    cells = [(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c != "."]
    x0, x1 = min(x for x, _ in cells), max(x for x, _ in cells) + 1
    y0, y1 = min(y for _, y in cells), max(y for _, y in cells) + 1
    dx, dy = (TILE - (x1 - x0)) // 2 - x0, (TILE - (y1 - y0)) // 2 - y0
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {TILE} {TILE}" width="128" height="128" shape-rendering="crispEdges">',
        "  <!-- Generated by luban/tools/luban_os_icon.py from kCraft0 in luban/host/luban-os/src/art/art.cpp; do not edit by hand. -->",
        f'  <rect width="{TILE}" height="{TILE}" rx="4" fill="{TILE_COLOR}" shape-rendering="geometricPrecision"/>',
    ]
    for y, r in enumerate(rows):
        x = 0
        while x < 16:
            c = r[x]
            run = 1
            while x + run < 16 and r[x + run] == c:
                run += 1
            if c != ".":
                if c not in colors:
                    sys.exit(f"{art}: kCraft0 uses '{c}', which badge() gives no colour")
                out.append(f'  <rect x="{x + dx:g}" y="{y + dy:g}" width="{run}" height="1" fill="{colors[c]}"/>')
            x += run
    out.append("</svg>")
    return "\n".join(out) + "\n"


def main() -> int:
    src = art.read_text(encoding="utf-8")
    made = svg(craftsman(src), palette(src))
    if "--check" in sys.argv[1:]:
        if icon.read_text(encoding="utf-8") != made:
            print(f"{icon.relative_to(root)} is not what kCraft0 makes: run python3 luban/tools/luban_os_icon.py")
            return 1
        print("luban-os icon: ok")
        return 0
    icon.write_text(made, encoding="utf-8")
    print(f"wrote {icon.relative_to(root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
